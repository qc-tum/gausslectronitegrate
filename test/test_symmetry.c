char* test_point_group_representation()
{
	for (int i = 0; i < 48; ++i)
	{
		for (int j = 0; j < 48; ++j)
		{
			struct imat3x3 prod;
			multiply_imat3x3(&rep_octahedral[i], &rep_octahedral[j], &prod);

			int k;
			for (k = 0; k < 48; ++k)
			{
				if (imat3x3_equal(&prod, &rep_octahedral[k])) {
					break;
				}
			}

			if (k == 48) {
				return "product of two octahedral point group representation matrices does not result in another representation matrix";
			}

			if (k != multiplication_table_octahedral[i][j]) {
				return "product of two octahedral point group representation matrices does not agree with matrix from reference multiplication table";
			}
		}
	}

	return 0;
}
