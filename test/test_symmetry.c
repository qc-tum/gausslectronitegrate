//________________________________________________________________________________________________________________________
///
/// \brief Multiply two integer matrices.
///
static void multiply_imat3x3(const struct imat3x3* s, const struct imat3x3* t, struct imat3x3* ret)
{
	for (int i = 0; i < 3; ++i)
	{
		for (int k = 0; k < 3; ++k)
		{
			ret->data[i][k] = 0;
			for (int j = 0; j < 3; j++) {
				ret->data[i][k] += s->data[i][j] * t->data[j][k];
			}
		}
	}
}


//________________________________________________________________________________________________________________________
///
/// \brief Test whether two integer matrices are equal.
///
static bool imat3x3_equal(const struct imat3x3* s, const struct imat3x3* t)
{
	for (int i = 0; i < 3; ++i) {
		for (int j = 0; j < 3; ++j) {
			if (s->data[i][j] != t->data[i][j]) {
				return false;
			}
		}
	}

	return true;
}


